/**
 * Shared Foundry glue of the tools area: the dice, the acting actor, the current world, the
 * world settings, folders, and the card poster. Every feature file of module/tools uses it.
 */
import { characteristicDM } from "../config.mjs";
import { skillRank } from "../play/api.mjs";
import { makeDice, randomDie } from "../shared/dice.mjs";
import { SYSTEM_ID, postCard, pickActors, resolveActor, setting } from "../shared/foundry.mjs";

/** World folder names of generated documents (AGENTS.md: "Spacer: <Kind>"). */
export const WORLD_FOLDER = "Spacer: Worlds";
/** Folder of generated NPC actors. */
export const NPC_FOLDER = "Spacer: NPCs";
/** Folder of generated patron actors. */
export const PATRON_FOLDER = "Spacer: Patrons";
/** Folder of generated creature actors. */
export const ANIMAL_FOLDER = "Spacer: Animals";

/** World setting: the id of the current world journal (the Toolkit's context). */
export const CURRENT_WORLD_SETTING = "toolsWorld";
/** World setting: planetside state, `{ weather }` (the last weather check). */
export const PLANETSIDE_SETTING = "toolsPlanetside";

/** A dice object backed by Foundry's random source (`CONFIG.Dice.randomUniform`). */
export function dice() {
  return makeDice(randomDie());
}

/**
 * The actor the procedures roll for: a targeted token, else a controlled token, else the user's
 * character (shared `pickActors`). Returns an Actor or null.
 */
export async function selectedActor() {
  const [actor] = await pickActors(game.user.character ? [game.user.character] : []);
  return actor ?? null;
}

/**
 * The actor of an API option: `undefined` means the selected actor; an Actor, Token, or UUID is
 * resolved (shared `resolveActor`); `null` means no actor.
 */
export async function actorOption(actor) {
  return actor === undefined ? selectedActor() : resolveActor(actor);
}

/** SOC DM of an actor (0 without one). */
export const socDMOf = actor => (actor?.system?.characteristics ? characteristicDM(actor.system.characteristics.soc.value) : 0);

/** Skill rank of an actor, at least 0 (0 without an actor). */
export const rankOf = (actor, skill) => (actor ? Math.max(0, skillRank(actor, skill)) : 0);

/** World journals generated by the tools (with flags.spacer.world), sorted by name. */
export function worldJournals() {
  return game.journal.filter(j => j.flags?.spacer?.world).sort((a, b) => a.name.localeCompare(b.name));
}

/** The structured world of a journal entry (flags.spacer.world), or null. */
export function worldOf(doc) {
  return doc?.flags?.spacer?.world ?? null;
}

/** The current world (the Toolkit's context), as stored world data or null. */
export function currentWorld() {
  const id = setting(CURRENT_WORLD_SETTING, "");
  return worldOf(id ? game.journal.get(id) : null);
}

/** Set the current world: a JournalEntry, its id, or null to clear it. GM only (world setting). */
export function setCurrentWorld(world) {
  return game.settings.set(SYSTEM_ID, CURRENT_WORLD_SETTING, world?.id ?? world ?? "");
}

/**
 * Map stored world data (flags.spacer.world) to the short context the rules use:
 * `{ name, starport, size, atmosphere, hydro, pop, gov, law, tl, codes, zone, temperature }`.
 */
export function worldContext(w) {
  if (!w) return null;
  return {
    name: w.name, starport: w.starport, size: w.size, atmosphere: w.atmosphere, hydro: w.hydrographics,
    pop: w.population, gov: w.government, law: w.law, tl: w.tl, codes: w.tradeCodes ?? [], zone: w.zone ?? "",
    temperature: w.temperature?.type ?? "Temperate"
  };
}

/**
 * Resolve a world option to the rules context: undefined or null (the current world), a
 * JournalEntry, a journal id, stored world data, or a context object (returned as is).
 */
export function resolveWorld(world) {
  if (world === undefined || world === null) return worldContext(currentWorld());
  if (typeof world === "string") return worldContext(worldOf(game.journal.get(world)));
  if (world.documentName === "JournalEntry") return worldContext(worldOf(world));
  if ("population" in world) return worldContext(world);
  return world;
}

/** Planetside state kept in the world setting `toolsPlanetside`. */
export function planetState() {
  return setting(PLANETSIDE_SETTING, {}) ?? {};
}

/** Merge `patch` into the planetside state. GM only; players skip the write. */
export async function setPlanetState(patch) {
  if (!game.user.isGM) return;
  await game.settings.set(SYSTEM_ID, PLANETSIDE_SETTING, { ...planetState(), ...patch });
}

/** Find or create a folder by name (and parent) for a document type. Returns the Folder. */
export async function ensureFolder(name, type, parent = null) {
  const parentId = parent?.id ?? parent ?? null;
  const found = game.folders.find(f => f.type === type && f.name === name && (f.folder?.id ?? null) === parentId);
  if (found) return found;
  return Folder.create({ name, type, folder: parentId, sorting: "a" });
}

/**
 * Post a tools chat card (templates/tools/card.hbs) with the shared `postCard`. `kind` and
 * `data` go to flags.spacer.tools, where the card buttons read them.
 */
export function postToolsCard(card, { kind = "", data = null, actor = null } = {}) {
  return postCard({ area: "tools", template: "card", data: card, actor, flags: { tools: { kind, data } } });
}
