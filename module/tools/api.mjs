/**
 * Generate a main world with its star system. Creates the journal entry unless `create` is false.
 */
export async function generateWorld({ name = "", hex = "0101", density = "typical", sizeMode = "standard", popDM = 0, create = true, folder = null, chat = true } = {}) {
  const w = worldRules.generateStarSystem(dice(), { name, hex, density, sizeMode, popDM });
  let journal = null;
  if (create) journal = await createWorldJournal(w, { folder });
  if (chat) await postCard(cards.worldCard(w, { uuid: journal?.uuid }), { kind: "world", data: journal ? null : w });
  return { world: w, journal };
}

/**
 * Generate a subsector: one journal entry per world in "Spacer: Worlds/<name>" plus an overview
 * journal entry.
 */
export async function generateSubsector({ name = "", density = "typical", sizeMode = "standard", chat = true } = {}) {
  const s = worldRules.generateSubsector(dice(), { name, density, sizeMode });
  const root = await ensureFolder(WORLD_FOLDER, "JournalEntry");
  const folder = await ensureFolder(s.name, "JournalEntry", root);
  const links = {};
  const docs = await JournalEntry.createDocuments(s.worlds.map(w => ({
    name: w.name,
    folder: folder.id,
    pages: [{ name: `${w.name} ${w.uwp}`, type: "text", text: { content: cards.worldPageHtml(w), format: CONST.JOURNAL_ENTRY_PAGE_FORMATS.HTML } }],
    flags: { spacer: { world: { ...w, subsector: s.name } } }
  })));
  for (const d of docs) links[d.name] = d.uuid;
  const summary = { ...s, worlds: s.worlds.map(w => ({ name: w.name, hex: w.hex, uwp: w.uwp, line: w.line, zone: w.zone, capital: !!w.capital })) };
  const overview = await JournalEntry.create({
    name: `${s.name} (overview)`,
    folder: folder.id,
    sort: -1,
    pages: [{ name: "Subsector map", type: "text", text: { content: cards.subsectorPageHtml(s, links), format: CONST.JOURNAL_ENTRY_PAGE_FORMATS.HTML } }],
    flags: { spacer: { subsector: summary } }
  });
  if (chat) {
    await postCard({
      title: "Subsector", subtitle: s.name, icon: "fa-solid fa-map",
      headline: `${s.worlds.length} worlds · capital ${s.capital ?? "none"}`,
      sections: [{ list: s.worlds.map(w => w.line) }],
      buttons: [{ action: "tools-open", uuid: overview.uuid, label: "Open overview", icon: "fa-solid fa-book-open" }]
    }, { kind: "subsector" });
  }
  return { subsector: s, folder, journals: docs, overview };
}

