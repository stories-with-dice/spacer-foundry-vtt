/* ---------------------------------------------------------------- encounters */

function lowestSoc() {
  const pcs = game.actors.filter(a => a.type === "character" && a.hasPlayerOwner);
  if (!pcs.length) return 7;
  return Math.min(...pcs.map(a => a.system.characteristics.soc.value));
}

export async function starportEncounter({ world, actor = selectedActor(), chat = true } = {}) {
  const w = resolveWorld(world) ?? {};
  const r = starportRules.starportEncounter(dice(), { world: w, lowestSoc: lowestSoc(), socDM: socDMOf(actor) });
  if (r.npc) r.npc.characteristics = npcRules.rollCharacteristics(dice(), { hits: r.npc.hits });
  if (chat) await postCard(cards.starportCard(r), { kind: "starport", data: r.npc ?? r, actor });
  return r;
}

