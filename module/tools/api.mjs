/* ---------------------------------------------------------------- chat card buttons */

/** Handle tools-* buttons on chat cards. */
export async function onCardAction(message, action, button) {
  const t = message.flags?.spacer?.tools ?? {};
  const data = t.data;
  switch (action) {
    case "tools-create-npc": {
      const a = await createNpcActor(data);
      return a?.sheet?.render(true);
    }
    case "tools-create-randomnpc": {
      if (!data?.who) return;
      const npc = { ...data, characteristics: data.characteristics ?? npcRules.rollCharacteristics(dice(), { hits: data.hits }) };
      const a = await createNpcActor(npc, { name: data.who });
      return a?.sheet?.render(true);
    }
    case "tools-create-patron": {
      const p = data.patron;
      const npc = { type: p.name, demeanour: p.demeanour, characteristics: npcRules.rollCharacteristics(dice()) };
      const notes = `<p>Personality: ${cards.esc(p.personality)}. Feature: ${cards.esc(p.feature)}.</p><p>Job: ${cards.esc(data.job.type)}: ${cards.esc(data.job.objectives.map(o => o.text).join("; "))}</p>`;
      const a = await createNpcActor(npc, { name: `${p.name} (patron)`, folder: PATRON_FOLDER, notes, flagKey: "patron", flagData: data });
      return a?.sheet?.render(true);
    }
    case "tools-create-creature": {
      const a = await createCreatureActor(data);
      return a?.sheet?.render(true);
    }
    case "tools-animal-here":
      return generateAnimal({ terrain: data?.terrain ?? "open" });
    case "tools-create-world": {
      if (!data) return;
      const j = await createWorldJournal(data);
      return j?.sheet?.render(true);
    }
    case "tools-open": {
      const doc = await fromUuid(button.dataset.uuid);
      return doc?.sheet?.render(true);
    }
  }
}
