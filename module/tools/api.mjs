/**
 * A survival activity (p.106-107) rolled with rollTask for the actor. `activity` is a key of
 * survivalRules.ACTIVITIES. Advances the clock by the activity time when `advance` is true.
 */
export async function survival(activity, { actor = selectedActor(), terrain = "open", inadequate = false, advance = true, skill = null } = {}) {
  const a = survivalRules.ACTIVITIES[activity];
  if (!a) throw new Error(`Unknown survival activity ${activity}`);
  // Weather survival DM (p.97) plus the temperature dice modification (p.96).
  const lw = lastWeather();
  const weatherDM = (lw?.survivalDM ?? 0) + (lw?.zoneDM ?? 0);
  const scores = {};
  for (const k of CHARACTERISTICS) scores[k] = actor?.system?.characteristics?.[k]?.value ?? 7;
  const characteristic = survivalRules.bestCharacteristic(a.characteristics, scores);
  const dm = survivalRules.activityDM(activity, { terrain, weatherDM, inadequate });
  const skillName = skill ?? a.skill ?? survivalRules.SURVIVAL_SKILL;
  const task = await rollTask({ actor, characteristic, skill: skillName, dm, label: `${a.label} (${planetRules.TERRAIN[terrain]?.label ?? terrain})` });
  const extra = [
    { label: "Roll", value: `${characteristic.toUpperCase()} + ${skillName} + terrain/weather DM ${dm >= 0 ? "+" : ""}${dm}` }
  ];
  let animal = null;
  if (task.success && activity === "hunting") {
    animal = animalRules.generateAnimal(dice(), { terrain: animalRules.ANIMAL_TERRAIN[terrain] ? terrain : "open" });
    extra.push({ label: "Animal", value: `${animal.name} (${animal.sizeLabel})` }, { label: "Rations", value: String(animal.hits) });
  }
  if (task.success && activity.startsWith("foraging")) {
    const f = survivalRules.forageAmount(dice(), { rank: actor ? Math.max(0, skillRank(actor, skillName)) : 0, terrain });
    extra.push({ label: activity === "foragingWater" ? "Water (days)" : "Food (rations)", value: `${f.amount} (${f.dice} ${f.roll})` });
  }
  await postCard(cards.survivalCard({ label: a.label, activity: a, task, extra }), { kind: "survival", data: animal, actor });
  if (advance && a.hours && game.user.isGM) await advanceClock(a.hours * 3600, { label: a.label, chat: false });
  return { task, animal };
}

export async function rations({ people = 1, days = 1, world, chat = true } = {}) {
  const w = resolveWorld(world);
  const r = survivalRules.rations({ people, days, pop: w?.pop ?? 6, hydro: w?.hydro ?? 5 });
  if (chat) {
    await postCard({
      title: "Food and water", subtitle: `${people} people x ${days} days (p.106)`, icon: "fa-solid fa-utensils",
      headline: `${cards.cr(r.total)}`,
      sections: [{ rows: [
        { label: "Food", value: `${r.foodKg} kg at ${cards.cr(r.foodCost)} per day` },
        { label: "Water", value: `${r.waterL} L at ${cards.cr(r.waterCost)} per day` }
      ], text: r.starvation }]
    }, { kind: "rations" });
  }
  return r;
}

