#!/usr/bin/env node
/**
 * Generate module/tools/rules/world-code-links.mjs: the compendium ids and the anchors of the
 * "25a World Codes" journal entry (src/content/rules/part2-25a-world-codes.json).
 *
 * The browser cannot compute the pack ids (stableId needs node:crypto), so this script reads the
 * ids that `buildAll` in tools/build-packs.mjs gives and writes them as plain data. The world
 * journal pages and the world chat card (module/tools/cards/) read that data to link each world
 * code to its definition. test/tools-cards.test.mjs fails when the file is out of date.
 *
 * Usage: node tools/gen-world-code-links.mjs [--check]
 * --check prints nothing and exits with 1 when the file on disk differs.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { buildAll } from "./build-packs.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const WORLD_CODES_ENTRY = "25a World Codes";
export const LINKS_FILE = join(ROOT, "module", "tools", "rules", "world-code-links.mjs");

/**
 * Anchors of one page: the ids of its headings, `<kind>-<code>`. Returns `{ kind, codes }`.
 * Every anchor of a page must share one kind.
 */
export function pageAnchors(html, pageName) {
  const ids = [...html.matchAll(/<h[1-6][^>]*\sid="([^"]+)"/g)].map(m => m[1]);
  const kinds = new Set(ids.map(id => id.slice(0, id.indexOf("-"))));
  if (kinds.size !== 1) throw new Error(`World Codes page "${pageName}": anchors need one kind, found ${[...kinds].join(", ") || "none"}`);
  return { kind: [...kinds][0], codes: ids.map(id => id.slice(id.indexOf("-") + 1)) };
}

/** The source text of module/tools/rules/world-code-links.mjs, from the built rules pack. */
export function worldCodeLinksSource(packs = buildAll()) {
  const entry = packs.rules.find(d => d.name === WORLD_CODES_ENTRY && d.pages);
  if (!entry) throw new Error(`rules pack has no journal entry "${WORLD_CODES_ENTRY}"`);
  const pages = {};
  for (const p of entry.pages) {
    const { kind, codes } = pageAnchors(p.text.content, p.name);
    if (pages[kind]) throw new Error(`World Codes: kind "${kind}" is on two pages`);
    pages[kind] = { page: p._id, name: p.name, codes };
  }
  const body = Object.entries(pages).map(([k, v]) => `  ${k}: { page: "${v.page}", name: "${v.name}", codes: ${JSON.stringify(v.codes)} }`).join(",\n");
  return `/**
 * GENERATED by tools/gen-world-code-links.mjs from src/content/rules/part2-25a-world-codes.json.
 * Do not edit: run \`node tools/gen-world-code-links.mjs\` after changing that file.
 *
 * Ids of the "${WORLD_CODES_ENTRY}" journal entry in the rules compendium and its pages. Each
 * page holds one kind of world code; each value has a heading with the id "<kind>-<code>"
 * (for example "government-7", "size-A", "trade-Ag"). Read by module/tools/cards/world-links.mjs.
 */

/** UUID of the "${WORLD_CODES_ENTRY}" journal entry. */
export const WORLD_CODES_UUID = "Compendium.spacer.rules.JournalEntry.${entry._id}";

/** Page id, page name, and the codes with an anchor, by kind of code. */
export const WORLD_CODE_PAGES = {
${body}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = worldCodeLinksSource();
  if (process.argv.includes("--check")) {
    const ok = existsSync(LINKS_FILE) && readFileSync(LINKS_FILE, "utf8") === src;
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(LINKS_FILE, src);
  console.log(`Wrote ${LINKS_FILE}`);
}
